function fillIntroTemplate(text, language) {
  const fullName =
    language === "hi" ? siteConfig.fullNameHi : siteConfig.fullName;

  return text
    .replaceAll("{fullName}", fullName)
    .replaceAll("{familiesGoal}", String(siteConfig.familiesGoal))
    .replaceAll("{experienceYears}", String(siteConfig.experienceYears))
    .replaceAll("{policyHolders}", String(siteConfig.policyHolders));
}

export function getAdvisorIntro(language) {
  const intro = siteConfig.advisorIntro[language] ?? siteConfig.advisorIntro.hi;

  return {
    sectionKicker: intro.sectionKicker,
    sectionTitle: intro.sectionTitle,
    sectionDescription: fillIntroTemplate(intro.sectionDescription, language),
    thankYou: intro.thankYou,
    paragraphs: intro.paragraphs.map((paragraph) =>
      fillIntroTemplate(paragraph, language),
    ),
    planningTitle: intro.planningTitle,
    planningItems: intro.planningItems,
    customers: intro.customers,
  };
}

